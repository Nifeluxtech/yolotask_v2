#!/usr/bin/env bash
# Rebuilds the committed per-portal assets from the shared sources.
# Run after editing shared/assets/*; the output is committed so cPanel needs no build step.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
for role in main earner advertiser reviewer admin; do
  dir="apps/${role}/public/assets"
  mkdir -p "$dir/css" "$dir/js"
  {
    echo "@import url('https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800;900&display=swap');"
    echo "/* Generated by scripts/build-assets.sh from shared/assets/css. Do not edit directly. */"
    cat shared/assets/css/yolotask.css shared/assets/css/components.css shared/assets/css/signature.css
  } > "$dir/css/app.css"
  { echo "/* Generated by scripts/build-assets.sh from shared/assets/js/yolotask.js. Do not edit directly. */"; cat shared/assets/js/yolotask.js; } > "$dir/js/ui.js"
done
echo "Assets rebuilt for all portals."
