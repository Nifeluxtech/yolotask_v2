    /** Banks sorted by name for a select list: [code => name]. PHP turns the numeric codes into int keys; cast with (string). */
    public static function options(): array
    {
        $banks = self::BANKS;
        uasort($banks, static fn (string $a, string $b): int => strcasecmp($a, $b));
        return $banks;
    }

    public static function isValid(string $code): bool
    {
        return preg_match('/^8000\d{4}$/', $code) === 1 && isset(self::BANKS[$code]);
    }

    public static function name(string $code): ?string
    {
        return self::BANKS[$code] ?? null;
    }
